create table if not exists public.sevenrise_ai_messages (
  id bigint generated by default as identity primary key,
  telegram_user_id bigint not null,
  telegram_chat_id bigint not null,
  role text not null check (role in ('user', 'assistant')),
  content text not null,
  created_at timestamptz not null default now()
);

create index if not exists sevenrise_ai_messages_user_created_idx
  on public.sevenrise_ai_messages (telegram_user_id, created_at desc);

alter table public.sevenrise_ai_messages enable row level security;

-- No client-facing policies: only the Edge Function's service role accesses this table.
